let a = 10;
let b = 5;

// Addition
let sum = a + b;
console.log("Sum: " + sum);

// Subtraction
let difference = a - b;
console.log("Difference: " + difference);

// Multiplication
let product = a * b;
console.log("Product: " + product);

// Division
let quotient = a / b;
console.log("Quotient: " + quotient);

//remainder
let remainder = a % b;
console.log("Remainder: " + remainder);

//exponentiation
let exponentiation = a ** b;
console.log("Exponentiation: " + exponentiation);

//increment
a++;
console.log("Incremented a: " + a);

//decrement
b--;
console.log("Decremented b: " + b);

//comparison
let isEqual = a == b;
console.log("Is a equal to b? " + isEqual);

let isGreater = a > b;
console.log("Is a greater than b? " + isGreater);

let isLess = a < b;
console.log("Is a less than b? " + isLess); 

//logical operators
let isTrue = true;
let isFalse = false;

let andResult = isTrue && isFalse;
console.log("Logical AND: " + andResult);

let orResult = isTrue || isFalse;
console.log("Logical OR: " + orResult);     

//not operator
let notResult = !isTrue;
console.log("Logical NOT: " + notResult);   

//ternary operator
let ternaryResult = (a > b) ? "a is greater than b" : "a is not greater than b";
console.log("Ternary Result: " + ternaryResult);

//bitwise operators
let bitwiseAnd = a & b;
console.log("Bitwise AND: " + bitwiseAnd);  
